/** The three actions that need a reason before they are allowed to happen. */
type ReasonAction = "pause" | "block" | "close" | "escalateToCarrier";

const REASON_PROMPT: Record<ReasonAction, { title: string; placeholder: string; confirm: string }> = {
  pause: {
    title: "Why are you putting this down?",
    placeholder: "Waiting on the carrier to call back",
    confirm: "Pause for 8 hours",
  },
  block: {
    title: "What is standing in the way?",
    placeholder: "Insurance lapsed on the carrier side",
    confirm: "Block this loop",
  },
  close: {
    title: "Why are you closing this cycle?",
    placeholder: "Carrier took the truck back",
    confirm: "Close this loop",
  },
  escalateToCarrier: {
    // The one action that crosses an organization boundary, so the wording
    // says out loud what it does and what it does not do.
    title: "What do you need the carrier to decide?",
    placeholder: "Broker wants $200 over your floor. Your call.",
    confirm: "Escalate to the carrier",
  },
};

/**
 * How much one piece of evidence is worth, at a glance.
 *
 * `inferred` is deliberately not a success tone: a geofence suggesting a truck
 * is empty and a driver saying so are different things to book a load against.
 */
const EVIDENCE_TONE: Record<FactVerification, "neutral" | "info" | "success" | "warning" | "danger"> = {
  confirmed: "success",
  corrected: "success",
  inferred: "info",
  extracted: "info",
  pending: "warning",
  rejected: "danger",
  failed: "danger",
};

export interface LoopActionHandlers {
  onClaim: () => void;
  onRelease: () => void;
  onAssign: (membershipId: string, name: string) => void;
  onPause: (reason: string) => void;
  onResume: () => void;
  onBlock: (reason: string) => void;
  onUnblock: () => void;
  onClose: (reason: string) => void;
  onEscalateToCarrier: (reason: string) => void;
}

/**
 * The cycle's own controls, and why the board says what it says.
 *
 * ★ THE CARD CARRIES ONE ACTION. THIS CARRIES THE REST. ★
 * A board that offers six buttons on every card is a board nobody works from —
 * but taking a loop, handing it over, putting it down and closing it are all
 * real and all have to stay reachable. They live one click away, together,
 * beside the evidence for the state they act on.
 *
 * Every button below is rendered from `card.can`, which the service worked out
 * beside the records. This component asks no question about roles and makes no
 * judgement, and each action is re-checked inside the service, so a board left
 * open in a tab cannot be used to do something the person may no longer do.
 */
export function LoopActionsDialog({
  card, assignableTo, busy, handlers, onClose,
}: {
  card: MtLoopCard;
  assignableTo?: Array<{ membershipId: string; name: string }>;
  busy: boolean;
  handlers: LoopActionHandlers;
  onClose: () => void;
}) {
  const [asking, setAsking] = useState<ReasonAction | null>(null);
  const [reason, setReason] = useState("");
  const [handing, setHanding] = useState(false);

  const others = (assignableTo ?? []).filter(
    (p) => p.membershipId !== card.claimed?.membershipId,
  );

  function submitReason() {
    const action = asking;
    const text = reason.trim();
    if (!action || !text) return;
    setAsking(null);
    setReason("");
    onClose();
    if (action === "pause") handlers.onPause(text);
    else if (action === "block") handlers.onBlock(text);
    else if (action === "escalateToCarrier") handlers.onEscalateToCarrier(text);
    else handlers.onClose(text);
  }

  const act = (fn: () => void) => () => { onClose(); fn(); };

  return (
    <Dialog open onOpenChange={(open) => { if (!open) onClose(); }}>
      <DialogContent
        title={`Unit ${card.truckUnit}`}
        description={card.headline}
        className="max-w-lg"
      >
        <div className="mt-4 flex flex-wrap items-center gap-2">
          {card.can.claim ? (
            <Button variant="primary" size="sm" disabled={busy} onClick={act(handlers.onClaim)}>
              Take it
            </Button>
          ) : null}
          {card.isMine ? (
            <Button variant="secondary" size="sm" disabled={busy} onClick={act(handlers.onRelease)}>
              Let it go
            </Button>
          ) : null}
          {(card.can.assign || card.can.reassign) && others.length > 0 ? (
            <Button variant="secondary" size="sm" disabled={busy} onClick={() => setHanding((v) => !v)}>
              {card.can.reassign ? "Hand over" : "Give to…"}
            </Button>
          ) : null}
          {card.can.resume ? (
            <Button variant="secondary" size="sm" disabled={busy} onClick={act(handlers.onResume)}>
              Resume
            </Button>
          ) : null}
          {card.can.pause ? (
            <Button variant="ghost" size="sm" disabled={busy} onClick={() => setAsking("pause")}>
              Pause
            </Button>
          ) : null}
          {card.can.unblock ? (
            <Button variant="secondary" size="sm" disabled={busy} onClick={act(handlers.onUnblock)}>
              Unblock
            </Button>
          ) : null}
          {card.can.block ? (
            <Button variant="ghost" size="sm" disabled={busy} onClick={() => setAsking("block")}>
              Block
            </Button>
          ) : null}
          {card.can.escalateToCarrier ? (
            <Button
              variant="ghost"
              size="sm"
              disabled={busy}
              onClick={() => setAsking("escalateToCarrier")}
            >
              Ask the carrier
            </Button>
          ) : null}
          {card.can.close ? (
            <Button variant="ghost" size="sm" disabled={busy} onClick={() => setAsking("close")}>
              Close
            </Button>
          ) : null}
        </div>

        {handing && others.length > 0 ? (
          <div className="mt-3 rounded-md border border-border bg-surface-sunken px-3 py-2.5">
            <p className="text-[0.75rem] font-medium text-fg">Hand this loop to</p>
            <div className="mt-2 flex flex-wrap gap-2">
              {others.map((person) => (
                <Button
                  key={person.membershipId}
                  variant="secondary"
                  size="sm"
                  disabled={busy}
                  onClick={() => {
                    setHanding(false);
                    onClose();
                    handlers.onAssign(person.membershipId, person.name);
                  }}
                >
                  {person.name}
                </Button>
              ))}
              <Button variant="ghost" size="sm" onClick={() => setHanding(false)}>
                Not now
              </Button>
            </div>
          </div>
        ) : null}

        {asking ? (
          <div className="mt-3 rounded-md border border-border bg-surface-sunken px-3 py-2.5">
            <label
              htmlFor={`reason-${card.loopId}`}
              className="text-[0.75rem] font-medium text-fg"
            >
              {REASON_PROMPT[asking].title}
            </label>
            <div className="mt-2 flex flex-wrap items-center gap-2">
              <Input
                id={`reason-${card.loopId}`}
                value={reason}
                placeholder={REASON_PROMPT[asking].placeholder}
                onChange={(e) => setReason(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === "Enter") {
                    e.preventDefault();
                    submitReason();
                  }
                }}
                className="max-w-sm"
              />
              <Button
                variant="primary"
                size="sm"
                disabled={busy || !reason.trim()}
                onClick={submitReason}
              >
                {REASON_PROMPT[asking].confirm}
              </Button>
              <Button
                variant="ghost"
                size="sm"
                onClick={() => { setAsking(null); setReason(""); }}
              >
                Cancel
              </Button>
            </div>
            <p className="mt-1.5 text-[0.75rem] leading-relaxed text-fg-subtle">
              The reason is kept on the loop with your name and the time, and it is never
              overwritten.
            </p>
          </div>
        ) : null}

        {/* ---- Why the board says what it says ---- */}
        <div className="mt-4 border-t border-border pt-3">
          <p className="text-[0.75rem] font-semibold text-fg">Why it says that</p>

          {card.blockers.length > 0 ? (
            <ul className="mt-2 space-y-1">
              {card.blockers.map((b) => (
                <li key={b.key} className="text-[0.75rem] leading-relaxed">
                  <span
                    className={b.stopsDispatch ? "font-medium text-st-danger" : "font-medium text-fg"}
                  >
                    {b.label}
                  </span>
                  <span className="text-fg-subtle"> · {OWNER_LABEL[b.owner]}</span>
                  {b.stopsDispatch ? (
                    <span className="text-st-danger"> · stops dispatch</span>
                  ) : null}
                  <br />
                  {b.href ? (
                    <Link href={b.href} className="text-fg-muted underline-offset-4 hover:underline">
                      {b.detail}
                    </Link>
                  ) : (
                    <span className="text-fg-muted">{b.detail}</span>
                  )}
                </li>
              ))}
            </ul>
          ) : (
            <p className="mt-1 text-[0.75rem] text-fg-muted">
              Nothing is standing in this cycle&rsquo;s way.
            </p>
          )}

          {card.evidence.length > 0 ? (
            <ul className="mt-3 space-y-0.5">
              {card.evidence.map((e) => (
                <li
                  key={e.label + e.detail}
                  className="flex flex-wrap items-baseline gap-x-2 text-[0.75rem] leading-relaxed"
                >
                  <span className="font-medium text-fg">{e.label}</span>
                  <Badge tone={EVIDENCE_TONE[e.verification]}>
                    {FACT_VERIFICATION_LABEL[e.verification]}
                  </Badge>
                  <span className="text-fg-muted">
                    {e.href ? (
                      <Link href={e.href} className="underline-offset-4 hover:underline">
                        {e.detail}
                      </Link>
                    ) : (
                      e.detail
                    )}
                  </span>
                </li>
              ))}
            </ul>
          ) : null}

          <p className="mt-3 text-[0.75rem] leading-relaxed text-fg-subtle">
            {card.responsible ? (
              <>
                {card.isMine ? "You are" : `${card.responsible.displayName} is`} responsible
                {" · "}
                {ASSIGNMENT_SOURCE_LABEL[card.responsible.source].toLowerCase()}
              </>
            ) : (
              <span className="text-st-warning">Could not read who is responsible</span>
            )}
            {card.claimed
              ? card.claimed.isMine
                ? " · you claimed it"
                : ` · claimed by ${card.claimed.displayName}`
              : " · not claimed yet"}
            {card.handoffCount > 1 ? ` · ${card.handoffCount} hands so far` : ""}
          </p>
        </div>

        <div className="mt-4 flex flex-wrap items-center gap-2">
          <Button variant="secondary" size="sm" asChild>
            <Link href={`/dispatch/trucks/${card.truckId}`}>
              Open unit {card.truckUnit}
            </Link>
          </Button>
          <Button variant="ghost" size="sm" onClick={onClose}>
            Done
          </Button>
        </div>
      </DialogContent>
    </Dialog>
  );
}

/** Who has to act. Not who noticed. */
const OWNER_LABEL: Record<"carrier" | "driver" | "dispatcher", string> = {
  carrier: "the carrier clears this",
  driver: "the driver clears this",
  dispatcher: "yours to clear",
};
