/**
 * The panels that open OVER the board rather than instead of it.
 *
 * ★ WHY THESE ARE NOT PAGES ★
 * The whole card is a link to the truck, which is right — clicking a truck
 * should open that truck. But reading the reply a broker just sent is a glance,
 * not a destination, and a dispatcher who loses their place on the board to
 * take that glance stops scanning the board. So the card's primary button opens
 * one of these and the card's own link does not fire.
 *
 * Everything below is READ from the module that owns it, in this membership's
 * own context. Nothing here is a second copy, and where something is not built
 * these say so in words rather than showing a button that would refuse.
 */

const money = (cents?: number) =>
  cents === undefined
    ? "no figure"
    : `$${(cents / 100).toLocaleString(undefined, { maximumFractionDigits: 0 })}`;

const when = (iso: string) =>
  new Date(iso).toLocaleString(undefined, {
    month: "short", day: "numeric", hour: "numeric", minute: "2-digit",
  });

