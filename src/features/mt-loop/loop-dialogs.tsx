/**
 * What a broker said, in the order it was said, with how it reached us.
 *
 * ★ THE CHANNEL IS NOT DECORATION ★
 * A round generated by the sample market and a round a dispatcher typed in
 * after a phone call are worth completely different amounts, and one of them
 * did not happen. Every line says which, because a screen that let a sample
 * reply read like a real one would have somebody book against it.
 */
export function BrokerReplyDialog({
  card, negotiationId, ctx, onClose,
}: {
  card: MtLoopCard;
  negotiationId: string;
  ctx: MtLoopContext | null;
  onClose: () => void;
}) {
  const q = useQuery({
    queryKey: ["mt-loop-negotiation", negotiationId, ctx?.membershipId],
    queryFn: async () => negotiationById(negotiationId, ctx!) ?? null,
    enabled: Boolean(ctx),
  });
  const n = q.data ?? undefined;

  return (
    <Dialog open onOpenChange={(open) => { if (!open) onClose(); }}>
      <DialogContent
        title={n ? `${n.brokerName} on unit ${card.truckUnit}` : `Unit ${card.truckUnit}`}
        description={n ? NEGOTIATION_STATUS_LABEL[n.status] : undefined}
        className="max-w-lg"
      >
        {q.isPending ? (
          <p className="mt-3 text-[0.8125rem] text-fg-muted">Reading the conversation…</p>
        ) : !n ? (
          // A conversation this membership may not read and one that is not
          // there are deliberately one answer.
          <p className="mt-3 text-[0.8125rem] leading-relaxed text-fg-muted">
            That conversation is not readable from here any more.
          </p>
        ) : (
          <>
            <p className="mt-3 flex flex-wrap items-center gap-x-3 gap-y-1 text-[0.8125rem] text-fg">
              <span className="font-medium">
                {money(n.agreedRateCents ?? n.onTheTableCents)} on the table
              </span>
              <span className="text-fg-subtle">asked {money(n.askedRateCents)}</span>
              {n.postedRateCents !== undefined ? (
                <span className="text-fg-subtle">posted {money(n.postedRateCents)}</span>
              ) : null}
              {n.offerExpiresAt ? (
                <span className="text-fg-subtle">good until {when(n.offerExpiresAt)}</span>
              ) : null}
            </p>

            <ul className="mt-3 max-h-64 space-y-2 overflow-y-auto pr-1">
              {[...n.rounds].reverse().map((round) => (
                <li
                  key={round.id}
                  className="rounded-md border border-border bg-surface-sunken px-3 py-2"
                >
                  <p className="flex flex-wrap items-center gap-x-2 gap-y-0.5 text-[0.75rem]">
                    <span className="font-medium text-fg">
                      {round.side === "broker" ? round.byName : `${round.byName} (us)`}
                    </span>
                    <span className="text-fg-muted">
                      {NEGOTIATION_ROUND_LABEL[round.kind]}
                    </span>
                    {round.amountCents !== undefined ? (
                      <span className="font-medium tabular-nums text-fg">
                        {money(round.amountCents)}
                      </span>
                    ) : null}
                    <span className="text-fg-subtle">{when(round.at)}</span>
                    {/* Said out loud, never implied. */}
                    <Badge tone={round.channel === "sample_reply" ? "warning" : "neutral"}>
                      {NEGOTIATION_CHANNEL_LABEL[round.channel]}
                    </Badge>
                  </p>
                  {round.note ? (
                    <p className="mt-1 text-[0.8125rem] leading-relaxed text-fg-muted">
                      {round.note}
                    </p>
                  ) : null}
                </li>
              ))}
            </ul>

            <div className="mt-4 flex flex-wrap items-center gap-2">
              {/*
                Answering, countering and taking a price all happen on the
                truck's own page, where the floor, the deadhead and the driver's
                answer are on the screen beside them. Offering them here, with
                none of that in view, would be offering a decision without the
                things it has to be made against.
              */}
              <Button variant="primary" size="sm" asChild>
                <Link href={`/dispatch/trucks/${card.truckId}`}>
                  Answer it on unit {card.truckUnit}
                </Link>
              </Button>
              <Button variant="ghost" size="sm" onClick={onClose}>
                Close
              </Button>
            </div>
          </>
        )}
      </DialogContent>
    </Dialog>
  );
}

