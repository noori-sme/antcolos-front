/**
 * Where the paper on a booked load has got to.
 *
 * ★ NOTHING IS SENT FROM HERE, AND THE PANEL SAYS SO ★
 * "Chase the rate con" is the name of the state, not a promise that a message
 * goes out: no mailbox is connected, so nothing in Antcolos can send or receive
 * one. What this shows is what has actually arrived, what is left to check, and
 * where the checking is done. A button that pretended to chase would be the
 * worst kind of lie on a screen about an unfinished load.
 */
export function RateConDialog({
  card, ctx, onClose,
}: {
  card: MtLoopCard;
  ctx: MtLoopContext | null;
  onClose: () => void;
}) {
  const q = useQuery({
    queryKey: ["mt-loop-ratecon", card.loopId, ctx?.membershipId],
    queryFn: async () => rateConForCycle(card.loopId, ctx!) ?? null,
    enabled: Boolean(ctx),
  });
  const w = q.data ?? undefined;

  return (
    <Dialog open onOpenChange={(open) => { if (!open) onClose(); }}>
      <DialogContent
        title={`${card.loadReference ?? "The booked load"} on unit ${card.truckUnit}`}
        description={w ? RATECON_STATUS_LABEL[w.status] : undefined}
        className="max-w-lg"
      >
        {q.isPending ? (
          <p className="mt-3 text-[0.8125rem] text-fg-muted">Looking for the paper…</p>
        ) : !w ? (
          <>
            <p className="mt-3 text-[0.8125rem] leading-relaxed text-fg">
              Nothing has arrived for this load. Until a signed confirmation is back the
              load is not final and the driver has nothing to run.
            </p>
            <p className="mt-2 text-[0.75rem] leading-relaxed text-fg-subtle">
              No mailbox is connected to Antcolos, so nothing here can send a chaser or
              notice one arriving by itself. A rate confirmation is recorded when somebody
              puts it in.
            </p>
          </>
        ) : (
          <>
            <p className="mt-3 text-[0.8125rem] leading-relaxed text-fg">
              From {w.brokerName}, {when(w.createdAt)}.{" "}
              {w.fields.filter((f) => f.reviewedAt).length} of {w.fields.length} fields
              checked.
            </p>
            {w.rejectedReason ? (
              <p className="mt-2 text-[0.8125rem] leading-relaxed text-st-danger">
                Stopped: {w.rejectedReason}
              </p>
            ) : null}
          </>
        )}

        <div className="mt-4 flex flex-wrap items-center gap-2">
          <Button variant="primary" size="sm" asChild>
            <Link href={`/dispatch/trucks/${card.truckId}`}>
              Open unit {card.truckUnit}
            </Link>
          </Button>
          {card.loadReference ? (
            <Button variant="secondary" size="sm" asChild>
              <Link href="/rate-cons">All rate confirmations</Link>
            </Button>
          ) : null}
          <Button variant="ghost" size="sm" onClick={onClose}>
            Close
          </Button>
        </div>
      </DialogContent>
    </Dialog>
  );
}

