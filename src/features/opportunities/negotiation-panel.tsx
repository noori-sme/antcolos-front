type BookCheckLike = ReturnType<typeof canBook>;

function NegotiationRow({
  summary, booking, busy, onCounter, onTheirReply, onSampleReply, onAccept,
  onWalkAway, onBook, bookCheck, onConsent,
}: {
  summary: NegotiationSummary;
  booking?: BookingRecord;
  busy: boolean;
  onCounter: (amountCents: number, note?: string) => void;
  onTheirReply: (input: {
    kind: "counter" | "accepted" | "declined";
    amountCents?: number;
    channel: "recorded_by_hand";
    note?: string;
  }) => void;
  onSampleReply: () => void;
  onAccept: (reason?: string) => void;
  onWalkAway: (reason: string) => void;
  onBook: () => void;
  bookCheck?: BookCheckLike;
  onConsent: (answer: "accepted" | "declined") => void;
}) {
  const n = summary.negotiation;
  const [open, setOpen] = useState(n.status === "waiting_on_you" || n.status === "agreed");
  const [form, setForm] = useState<"none" | "counter" | "their_reply" | "walk" | "below_floor" | "book">("none");
  const [amount, setAmount] = useState("");
  const [note, setNote] = useState("");

  const live = ["waiting_on_broker", "waiting_on_you", "agreed"].includes(n.status);
  const onTable = n.agreedRateCents ?? n.onTheTableCents;
  const belowFloor = summary.carrierFloorPerMileCents !== undefined
    && summary.onTheTablePerMileCents !== undefined
    && summary.onTheTablePerMileCents < summary.carrierFloorPerMileCents;

  const dollarsToCents = (v: string) => Math.round(Number.parseFloat(v || "0") * 100);

  return (
    <li className={cn(
      "rounded-md border bg-surface-sunken px-3.5 py-3",
      n.status === "agreed" ? "border-st-success/45"
        : n.status === "waiting_on_you" ? "border-primary/40"
          : "border-border",
      !live && "opacity-75",
    )}
    >
      <div className="flex flex-wrap items-start justify-between gap-x-4 gap-y-2">
        <div className="min-w-0">
          <p className="flex flex-wrap items-center gap-2 text-[0.8125rem] font-medium text-fg">
            {summary.lane.split(" → ")[0]}
            <ArrowRight className="size-3.5 shrink-0 text-fg-subtle" aria-hidden />
            {summary.lane.split(" → ")[1]}
            <Badge tone={
              n.status === "agreed" ? "success"
                : n.status === "waiting_on_you" ? "info"
                  : n.status === "booked" ? "success" : "outline"
            }
            >
              {NEGOTIATION_STATUS_LABEL[n.status]}
            </Badge>
            <span className="text-[0.75rem] font-normal text-fg-muted">Unit {n.truckUnit}</span>
          </p>
          <p className="mt-0.5 text-[0.75rem] text-fg-muted">
            {n.brokerName}
            {n.brokerContactName ? ` · ${n.brokerContactName}` : ""}
            {" · under "}
            {n.carrierName}
          </p>
          <p className="mt-1 flex flex-wrap items-center gap-x-3 gap-y-0.5 text-[0.75rem] text-fg-muted">
            {n.postedRateCents !== undefined ? <span>Posted {money(n.postedRateCents)}</span> : null}
            <span>You asked {money(n.askedRateCents)}</span>
            {onTable !== undefined ? (
              <span className="font-medium text-fg">
                {n.status === "agreed" || n.status === "booked" ? "Agreed" : "On the table"} {money(onTable)}
                {summary.onTheTablePerMileCents !== undefined
                  ? ` · ${ratePerMile(summary.onTheTablePerMileCents)}`
                  : ""}
              </span>
            ) : null}
          </p>
          {belowFloor && summary.carrierFloorPerMileCents !== undefined ? (
            <p className="mt-1 text-[0.75rem] leading-relaxed text-st-warning">
              That is under {n.carrierName}&apos;s floor of {ratePerMile(summary.carrierFloorPerMileCents)}.
              {n.belowFloorReason ? ` Taken anyway: ${n.belowFloorReason}` : " Taking it needs a reason."}
            </p>
          ) : null}
          {n.offerExpiresAt && n.status === "waiting_on_you" ? (
            <p className="mt-1 text-[0.75rem] text-st-warning">
              Their number is good for {relativeTime(n.offerExpiresAt)}.
            </p>
          ) : null}
          {n.outcomeNote && !live ? (
            <p className="mt-1 text-[0.75rem] leading-relaxed text-fg-muted">{n.outcomeNote}</p>
          ) : null}
        </div>

        <div className="flex shrink-0 flex-wrap justify-end gap-1.5">
          {n.status === "waiting_on_broker" ? (
            <>
              <Button variant="secondary" size="sm" disabled={busy} onClick={() => { setForm("their_reply"); setAmount(""); setNote(""); }}>
                <Phone className="size-3.5" aria-hidden />
                They answered
              </Button>
              <Button variant="ghost" size="sm" disabled={busy} onClick={onSampleReply}>
                Sample reply
              </Button>
            </>
          ) : null}
          {n.status === "waiting_on_you" ? (
            <>
              <Button
                variant="primary"
                size="sm"
                disabled={busy}
                onClick={() => (belowFloor ? setForm("below_floor") : onAccept())}
              >
                Take it
              </Button>
              <Button variant="secondary" size="sm" disabled={busy} onClick={() => { setForm("counter"); setAmount(""); setNote(""); }}>
                Counter
              </Button>
            </>
          ) : null}
          {n.status === "agreed" ? (
            <Button variant="primary" size="sm" disabled={busy} onClick={() => setForm("book")}>
              Book it
            </Button>
          ) : null}
          {live ? (
            <Button variant="ghost" size="sm" disabled={busy} onClick={() => { setForm("walk"); setNote(""); }}>
              Walk away
            </Button>
          ) : null}
          <Button variant="ghost" size="sm" onClick={() => setOpen((v) => !v)}>
            {open ? "Hide" : "The conversation"}
          </Button>
        </div>
      </div>

      {booking ? <BookedSummary booking={booking} busy={busy} onConsent={onConsent} /> : null}

      {form === "counter" || form === "their_reply" ? (
        <div className="mt-3 rounded-md border border-border bg-surface px-3 py-2.5">
          <p className="text-[0.75rem] font-medium text-fg">
            {form === "counter" ? "What are you going back with?" : `What did ${n.brokerContactName ?? n.brokerName} say?`}
          </p>
          <div className="mt-2 flex flex-wrap items-center gap-2">
            <Input
              inputMode="decimal"
              value={amount}
              placeholder="2350"
              aria-label="Amount in dollars"
              onChange={(e) => setAmount(e.target.value)}
              className="max-w-[10rem]"
            />
            <Input
              value={note}
              placeholder={form === "counter" ? "Best we can do on that lane" : "That is over my budget"}
              aria-label="What was said"
              onChange={(e) => setNote(e.target.value)}
              className="max-w-sm"
            />
            <Button
              variant="primary"
              size="sm"
              disabled={busy || !amount.trim()}
              onClick={() => {
                const cents = dollarsToCents(amount);
                if (form === "counter") onCounter(cents, note.trim() || undefined);
                else onTheirReply({ kind: "counter", amountCents: cents, channel: "recorded_by_hand", note: note.trim() || undefined });
                setForm("none");
              }}
            >
              Record it
            </Button>
            {form === "their_reply" ? (
              <>
                <Button
                  variant="secondary"
                  size="sm"
                  disabled={busy}
                  onClick={() => { onTheirReply({ kind: "accepted", channel: "recorded_by_hand", note: note.trim() || undefined }); setForm("none"); }}
                >
                  They took it
                </Button>
                <Button
                  variant="ghost"
                  size="sm"
                  disabled={busy}
                  onClick={() => { onTheirReply({ kind: "declined", channel: "recorded_by_hand", note: note.trim() || undefined }); setForm("none"); }}
                >
                  They said no
                </Button>
              </>
            ) : null}
            <Button variant="ghost" size="sm" onClick={() => setForm("none")}>Cancel</Button>
          </div>
          <p className="mt-2 text-[0.6875rem] leading-relaxed text-fg-subtle">
            Typed in by you, after a call or an email you had elsewhere. Antcolos does not send or
            read mail yet.
          </p>
        </div>
      ) : null}

      {form === "below_floor" ? (
        <Reason
          label={`${money(onTable ?? 0)} is under ${n.carrierName}'s floor. Why take it?`}
          placeholder="Repositioning to Boise for a better lane tomorrow"
          busy={busy}
          onCancel={() => setForm("none")}
          onSubmit={(reason) => { onAccept(reason); setForm("none"); }}
        />
      ) : null}

      {form === "walk" ? (
        <Reason
          label="Why are you walking away?"
          placeholder="They will not come off the posted rate"
          busy={busy}
          onCancel={() => setForm("none")}
          onSubmit={(reason) => { onWalkAway(reason); setForm("none"); }}
        />
      ) : null}

      {form === "book" ? (
        <BookConfirm
          check={bookCheck}
          busy={busy}
          onCancel={() => setForm("none")}
          onConfirm={() => { onBook(); setForm("none"); }}
        />
      ) : null}

      {open ? (
        <ol className="mt-3 space-y-1.5 border-t border-border pt-2.5">
          {n.rounds.map((round) => (
            <li key={round.id} className="flex flex-wrap items-baseline gap-x-2 gap-y-0.5 text-[0.75rem]">
              <span className={cn(
                "font-medium",
                round.side === "us" ? "text-fg" : "text-primary",
              )}
              >
                {round.byName}
              </span>
              <span className="text-fg-muted">{NEGOTIATION_ROUND_LABEL[round.kind]}</span>
              {round.amountCents !== undefined ? (
                <span className="font-medium tabular-nums text-fg">{money(round.amountCents)}</span>
              ) : null}
              {round.channel === "sample_reply" ? (
                <Badge tone="warning">Sample reply — no mailbox is connected</Badge>
              ) : null}
              <span className="text-fg-subtle">{relativeTime(round.at)}</span>
              {round.note ? (
                <span className="w-full text-fg-muted">{round.note}</span>
              ) : null}
            </li>
          ))}
        </ol>
      ) : null}
    </li>
  );
}

