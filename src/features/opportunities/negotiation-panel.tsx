/** One typed reason, required before something irreversible or unusual. */
function Reason({
  label, placeholder, busy, onCancel, onSubmit,
}: {
  label: string;
  placeholder: string;
  busy: boolean;
  onCancel: () => void;
  onSubmit: (reason: string) => void;
}) {
  const [value, setValue] = useState("");
  return (
    <div className="mt-3 rounded-md border border-border bg-surface px-3 py-2.5">
      <p className="text-[0.75rem] font-medium text-fg">{label}</p>
      <div className="mt-2 flex flex-wrap items-center gap-2">
        <Input
          value={value}
          placeholder={placeholder}
          aria-label={label}
          onChange={(e) => setValue(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && value.trim()) {
              e.preventDefault();
              onSubmit(value.trim());
            }
          }}
          className="max-w-sm"
        />
        <Button variant="primary" size="sm" disabled={busy || !value.trim()} onClick={() => onSubmit(value.trim())}>
          Record it
        </Button>
        <Button variant="ghost" size="sm" onClick={onCancel}>Cancel</Button>
      </div>
    </div>
  );
}

/**
 * What booking is about to do, said out loud before it is done.
 *
 * Committing a truck is the least reversible thing in the module: it creates a
 * load, assigns a driver, and kills every other conversation about the same
 * listing. A dispatcher is entitled to read all of that before clicking, and
 * the numbers here come from the same check the service runs, so the screen
 * cannot promise something different from what happens.
 */
function BookConfirm({
  check, busy, onCancel, onConfirm,
}: {
  check?: BookCheckLike;
  busy: boolean;
  onCancel: () => void;
  onConfirm: () => void;
}) {
  if (!check || !check.ok || !check.preview) {
    return (
      <div className="mt-3 rounded-md border border-st-danger/40 bg-st-danger-bg/50 px-3 py-2.5">
        <p className="text-[0.75rem] font-medium text-fg">This cannot be booked</p>
        <ul className="mt-1 space-y-0.5">
          {(check?.blocks ?? [{ kind: "not_agreed", detail: "Nothing is agreed yet." }]).map((b) => (
            <li key={b.kind} className="text-[0.75rem] leading-relaxed text-fg-muted">{b.detail}</li>
          ))}
        </ul>
        <Button variant="ghost" size="sm" className="mt-2" onClick={onCancel}>Close</Button>
      </div>
    );
  }

  const p = check.preview;
  return (
    <div className="mt-3 rounded-md border border-primary/40 bg-surface px-3 py-2.5">
      <p className="text-[0.8125rem] font-medium text-fg">Book {p.lane} on unit {p.truckUnit}?</p>
      <ul className="mt-1.5 space-y-0.5 text-[0.75rem] leading-relaxed text-fg-muted">
        <li>A load is created at {money(p.rateCents)} for {p.loadedMiles.toLocaleString()} loaded miles, under {p.carrierName}.</li>
        <li>
          {p.driverName || p.trailerUnit
            ? `Unit ${p.truckUnit}${p.trailerUnit ? `, trailer ${p.trailerUnit}` : ""}${p.driverName ? ` and ${p.driverName}` : ""} go on it.`
            : `Unit ${p.truckUnit} goes on it.`}
        </li>
        <li>
          {p.consent === "pending"
            ? `${p.driverName ?? "The driver"} has to accept before it is assigned — ${p.carrierName} requires it.`
            : p.consent === "not_required"
              ? "There is no driver on this truck yet, so nobody has to accept."
              : "No driver consent is required by this carrier."}
        </li>
        {p.otherMatchesClosing > 0 || p.draftsStandingDown > 0 ? (
          <li>
            {p.otherMatchesClosing} other truck{p.otherMatchesClosing === 1 ? "" : "s"} and{" "}
            {p.draftsStandingDown} prepared message{p.draftsStandingDown === 1 ? "" : "s"} about this
            load stand down.
          </li>
        ) : null}
        <li>{p.brokerName} is written on the load as given. It is not linked to a saved broker profile.</li>
      </ul>
      <div className="mt-2 flex flex-wrap gap-2">
        <Button variant="primary" size="sm" disabled={busy} onClick={onConfirm}>
          Book it
        </Button>
        <Button variant="ghost" size="sm" onClick={onCancel}>Not yet</Button>
      </div>
    </div>
  );
}

/** What happened after booking, and what it is still waiting for. */
function BookedSummary({
  booking, busy, onConsent,
}: {
  booking: BookingRecord;
  busy: boolean;
  onConsent: (answer: "accepted" | "declined") => void;
}) {
  return (
    <div className="mt-3 rounded-md border border-st-success/40 bg-surface px-3 py-2.5">
      <p className="flex flex-wrap items-center gap-2 text-[0.8125rem] font-medium text-fg">
        {booking.loadReference} is booked
        <Badge tone={booking.consent === "pending" ? "warning" : booking.consent === "declined" ? "danger" : "success"}>
          {/* "Not required by this carrier" would be a lie on a truck that has
              nobody on it: there is no driver to require anything of. */}
          {booking.consent === "not_required" && !booking.driverProfileId
            ? "No driver on the truck yet"
            : CONSENT_LABEL[booking.consent]}
        </Badge>
      </p>
      <p className="mt-0.5 text-[0.75rem] leading-relaxed text-fg-muted">
        {money(booking.agreedRateCents)} with {booking.brokerName}, booked by {booking.bookedByName}.
        {booking.closedMatchIds.length > 0
          ? ` ${booking.closedMatchIds.length} other match${booking.closedMatchIds.length === 1 ? "" : "es"} stood down.`
          : ""}
      </p>
      {booking.consent === "pending" ? (
        <div className="mt-2 flex flex-wrap items-center gap-2">
          <span className="text-[0.75rem] text-fg-muted">
            Did {booking.driverName ?? "the driver"} take it?
          </span>
          <Button variant="secondary" size="sm" disabled={busy} onClick={() => onConsent("accepted")}>
            They accepted
          </Button>
          <Button variant="ghost" size="sm" disabled={busy} onClick={() => onConsent("declined")}>
            They declined
          </Button>
        </div>
      ) : null}
      {booking.consent === "declined" ? (
        <p className="mt-1 text-[0.75rem] leading-relaxed text-st-danger">
          The truck is committed to {booking.brokerName} and has nobody to drive it. Somebody has to
          ring the broker.
        </p>
      ) : null}
      <p className="mt-2 text-[0.6875rem] leading-relaxed text-fg-subtle">
        The rate confirmation has not arrived. Receiving it, checking it and signing it is the next
        milestone; nothing about this load is emailed to anybody yet.
      </p>
    </div>
  );
}
