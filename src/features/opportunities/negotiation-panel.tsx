/**
 * The conversations about one truck, and what they have cost so far.
 *
 * Every round is shown, oldest last, with who said it and how it reached us.
 * A dispatcher scrolling this is answering one question — "where are we with
 * this broker" — and a screen that shows only the latest number cannot answer
 * it. The middle of a negotiation is where the information is: a broker who
 * came up twice will come up again.
 *
 * Nothing here emails anybody. A reply is either typed in by the person who
 * took the call, or generated by the same sample market the loads come from,
 * and each round says which it was.
 */
export function NegotiationPanel({
  negotiations, ctx, onChanged,
}: {
  negotiations: NegotiationSummary[];
  ctx: MtLoopContext | null;
  onChanged: () => void;
}) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function act(fn: () => Promise<{ status: string }>) {
    if (!ctx) return;
    setBusy(true);
    setError(null);
    const outcome = await fn().catch(() => null);
    setBusy(false);
    if (!outcome) setError("Something went wrong. Nothing was changed.");
    else if (outcome.status === "not_permitted") setError("You are not allowed to do that.");
    else if (outcome.status === "needs_reason") setError("That needs a reason in your own words.");
    else if (outcome.status === "listing_gone") setError("That load has gone. The conversation is closed.");
    else if (outcome.status === "closed") setError("That conversation is already finished.");
    onChanged();
  }

  const live = negotiations.filter((n) => ["waiting_on_broker", "waiting_on_you", "agreed"].includes(n.negotiation.status));
  const done = negotiations.filter((n) => !live.includes(n));

  return (
    <section className="rounded-lg border border-border bg-surface p-4 shadow-e1">
      <div className="flex flex-wrap items-start justify-between gap-x-4 gap-y-1">
        <div className="min-w-0">
          <h2 className="flex items-center gap-2 text-[0.875rem] font-semibold text-fg">
            <Handshake className="size-4 text-fg-subtle" aria-hidden />
            Talking to brokers
            {live.length > 0 ? (
              <span className="rounded-full bg-surface-sunken px-2 py-0.5 text-[0.6875rem] font-medium tabular-nums text-fg-muted">
                {live.length}
              </span>
            ) : null}
          </h2>
          <p className="mt-0.5 text-[0.75rem] leading-relaxed text-fg-muted">
            Every number either side has put on the table, in order. Nothing is emailed from here.
          </p>
        </div>
      </div>

      {error ? (
        <p role="alert" className="mt-3 rounded-md border border-st-danger/40 bg-st-danger-bg/60 px-3.5 py-2.5 text-[0.8125rem] text-fg">
          {error}
        </p>
      ) : null}

      {negotiations.length === 0 ? (
        <div className="mt-3 rounded-md border border-dashed border-border px-3.5 py-4 text-center">
          <p className="text-[0.8125rem] font-medium text-fg">No conversation is open</p>
          <p className="mt-0.5 text-[0.75rem] leading-relaxed text-fg-muted">
            Pick a load above and ask for it. What you ask, what they say back and what you settle
            on all stay here.
          </p>
        </div>
      ) : (
        <ul className="mt-3 space-y-2">
          {[...live, ...done].map((summary) => (
            <NegotiationRow
              key={summary.negotiation.negotiationId}
              summary={summary}
              booking={summary.booking}
              busy={busy}
              onCounter={(amount, note) =>
                void act(() => recordOurOffer(summary.negotiation.negotiationId, amount, ctx!, note))}
              onTheirReply={(input) =>
                void act(() => recordBrokerRound(summary.negotiation.negotiationId, input, ctx!))}
              onSampleReply={() =>
                void act(() => sampleBrokerReply(summary.negotiation.negotiationId, ctx!))}
              onAccept={(reason) =>
                void act(() => acceptOnTheTable(summary.negotiation.negotiationId, ctx!, reason))}
              onWalkAway={(reason) =>
                void act(() => walkAway(summary.negotiation.negotiationId, ctx!, reason))}
              onBook={() =>
                void act(async () => {
                  const out = await bookNegotiation(summary.negotiation.negotiationId, ctx!);
                  return out.status === "ok" ? { status: "ok" } : { status: "blocked" };
                })}
              bookCheck={ctx ? canBook(summary.negotiation.negotiationId, ctx) : undefined}
              onConsent={(answer) =>
                void act(() => recordDriverConsent(summary.booking!.bookingId, answer, ctx!))}
            />
          ))}
        </ul>
      )}
    </section>
  );
}

