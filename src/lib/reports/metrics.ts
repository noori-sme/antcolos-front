export type MetricKey = keyof typeof METRICS;

export function metricDefinition(key: string): MetricDefinition | undefined {
  return (METRICS as Record<string, MetricDefinition>)[key];
}

export function metricDefinitions(keys: readonly string[]): MetricDefinition[] {
  return keys
    .map((k) => metricDefinition(k))
    .filter((d): d is MetricDefinition => Boolean(d));
}
