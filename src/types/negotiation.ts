import type { Cents, IsoDateTime } from "./common";
import type { LoadStatus } from "./load";
import type { MatchCheckKey } from "./opportunity";

/**
 * Agreeing a price with a broker, and turning that agreement into a load.
 *
 * Two records, kept apart on purpose:
 *
 *   Negotiation  The conversation about ONE match — this listing, for THIS
 *                truck. It is a list of rounds, and a round is never edited or
 *                removed: "we asked $2,400, they came back with $2,150, we
 *                took $2,250" is the record, and the middle number matters as
 *                much as the last one. A negotiation belongs to the same
 *                dispatch cycle as the match, so everything that happens to
 *                the truck between going empty and being released hangs off
 *                one id.
 *
 *   Booking      What was done with an agreement: the load that was created,
 *                who confirmed it, the truck, trailer and driver put on it,
 *                and whether the driver's consent was required and given. A
 *                negotiation can be agreed and NOT booked — the truck broke,
 *                the driver said no — and those are different facts.
 *
 * Nothing here sends or receives anything. Broker replies come from the same
 * sample market the listings come from, and say so on screen.
 */

/* -------------------------------------------------------------------------- */
/* Rounds                                                                      */
/* -------------------------------------------------------------------------- */

/** Who moved. Never inferred from the round's content. */
export type NegotiationSide = "us" | "broker";

export type NegotiationRoundKind =
  /** The conversation was opened, with what we are asking for. */
  | "opened"
  /** A price was put on the table by whoever is named. */
  | "offer"
  /** A price was put on the table against one already there. */
  | "counter"
  /** The price on the table was taken. */
  | "accepted"
  /** The price on the table was refused, and the conversation is over. */
  | "declined"
  /** We walked away. */
  | "withdrawn"
  /** Nobody answered in time. */
  | "expired"
  /** Something said that is not a price: an appointment, a detention term. */
  | "note";

export const NEGOTIATION_ROUND_LABEL: Record<NegotiationRoundKind, string> = {
  opened: "Asked",
  offer: "Offered",
  counter: "Countered",
  accepted: "Agreed",
  declined: "Refused",
  withdrawn: "Walked away",
  expired: "Ran out of time",
  note: "Said",
};

/**
 * How a round reached us.
 *
 * This is the honest part. A round that came from the sample market must never
 * be shown as if a broker really wrote it, and a round somebody typed in after
 * a phone call is the most trustworthy kind there is — it happened, and a
 * person is standing behind it.
 */
export type NegotiationChannel =
  /** A message prepared in Antcolos and marked as sent by a person. */
  | "prepared_message"
  /** Generated by the sample market. Labelled as such wherever it is shown. */
  | "sample_reply"
  /** A person spoke to the broker and typed in what was said. */
  | "recorded_by_hand";

export const NEGOTIATION_CHANNEL_LABEL: Record<NegotiationChannel, string> = {
  prepared_message: "From the prepared message",
  sample_reply: "Sample reply",
  recorded_by_hand: "Recorded by hand",
};

/** One thing that was said, by one side, at one time. Never edited. */
export interface NegotiationRound {
  id: string;
  at: IsoDateTime;
  side: NegotiationSide;
  kind: NegotiationRoundKind;
  channel: NegotiationChannel;
  /** The whole load, not per mile. Absent on a note. */
  amountCents?: Cents;
  /** Who did it: a person's name for our side, the broker contact for theirs. */
  byName: string;
  /** Our side only: the membership that acted, for the audit trail. */
  actorMembershipId?: string;
  note?: string;
}

/* -------------------------------------------------------------------------- */
/* The negotiation                                                             */
/* -------------------------------------------------------------------------- */

export type NegotiationStatus =
  /** Open, and the ball is with the broker. */
  | "waiting_on_broker"
  /** Open, and the ball is with us. */
  | "waiting_on_you"
  /** A price is agreed. Nothing is booked yet. */
  | "agreed"
  /** Agreed and turned into a load. */
  | "booked"
  /** The broker said no, or gave it to somebody else. */
  | "lost"
  /** We walked away. */
  | "withdrawn"
  /** Nobody answered in time. */
  | "expired";

export const NEGOTIATION_STATUS_LABEL: Record<NegotiationStatus, string> = {
  waiting_on_broker: "Waiting on the broker",
  waiting_on_you: "Waiting on you",
  agreed: "Agreed",
  booked: "Booked",
  lost: "Lost",
  withdrawn: "Walked away",
  expired: "Ran out of time",
};

export const NEGOTIATION_OPEN_STATUSES: readonly NegotiationStatus[] = [
  "waiting_on_broker",
  "waiting_on_you",
  "agreed",
];

export function isNegotiationOpen(status: NegotiationStatus): boolean {
  return NEGOTIATION_OPEN_STATUSES.includes(status);
}

/**
 * One conversation about one match.
 *
 * `dispatchCycleId` is the MT Loop's id, exactly as it is on the match and the
 * search session. It is what makes "what happened to this truck this time
 * round" answerable in one query rather than four.
 */
export interface Negotiation {
  negotiationId: string;
  /** The dispatch workspace running the conversation. */
  organizationId: string;
  /** The carrier whose authority the load would run under. */
  carrierOrganizationId: string;
  carrierName: string;
  matchId: string;
  listingId: string;
  dispatchCycleId: string;
  truckId: string;
  truckUnit: string;

  status: NegotiationStatus;
  brokerName: string;
  brokerContactName?: string;
  brokerEmail?: string;

  /** What the load was posted at, kept so movement is visible. */
  postedRateCents?: Cents;
  /** What we opened with. */
  askedRateCents: Cents;
  /** The price currently on the table, whoever put it there. */
  onTheTableCents?: Cents;
  /** Set only when the status is agreed or booked. */
  agreedRateCents?: Cents;
  /** Recorded when a price under the carrier's floor was accepted anyway. */
  belowFloorReason?: string;

  /** When the price on the table stops being good. */
  offerExpiresAt?: IsoDateTime;
  openedAt: IsoDateTime;
  openedByName: string;
  closedAt?: IsoDateTime;
  /** Why it ended, in the operator's words. */
  outcomeNote?: string;

  rounds: NegotiationRound[];
}

/**
 * The checks no conversation can fix.
 *
 * A rate is an opinion and a deadhead limit is a judgement — both are what
 * negotiating is FOR, and refusing to let a dispatcher argue them would make
 * this module useless. A sprinter van will still not be a flatbed after the
 * phone call, the driver's licence will still be expired, and no broker can
 * grant operating authority. A match failing one of these cannot be opened.
 */
export const UNARGUABLE_CHECKS: readonly MatchCheckKey[] = [
  "operating_authority",
  "equipment",
  "capacity",
  "hazmat",
  "documents",
  "hours_of_service",
];

